def banner(version, nodes):
    return f"{ART}\n[Prompto] ComfyUI-Prompto {version} loaded · {nodes} nodes"


def show(version, nodes, out=None):
    """Prints the banner. A console that can't show Braille (some Windows code
    pages) gets the one-line version instead of an error during startup."""
    import sys
    out = out or sys.stdout
    try:
        print(banner(version, nodes), file=out, flush=True)
    except (UnicodeEncodeError, UnicodeError):
        print(f"[Prompto] ComfyUI-Prompto {version} loaded - {nodes} nodes", file=out, flush=True)
